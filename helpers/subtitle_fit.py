"""Give SRT subtitles a size that suits the video before they are muxed.

A plain SRT has no style or resolution, so every player (and every bot that
burns subtitles in) picks its own font size. On a 1080p video the default
often comes out far too large and fills the screen.

We convert an SRT into ASS with:
  * PlayResX / PlayResY equal to the video's resolution, so the font size is
    relative to the video frame, not to a fixed 288-pixel default;
  * a font size, outline and bottom margin that are fixed fractions of the
    video height, so the subtitles look the same at 480p, 720p or 1080p;
  * the original text, with size overrides removed so a single cue can not
    blow up the whole screen.

ASS / SSA files are left alone because their author already chose the styling.
"""

import asyncio
import os
import re
from typing import List, Optional, Tuple

from __init__ import LOGGER

# Fractions of the video height / width.
FONT_SIZE_RATIO = 0.06   # 1080p -> 65 px, close to the reference screenshot
OUTLINE_RATIO = 0.003    # 1080p -> 3 px
MARGIN_V_RATIO = 0.05    # distance from the bottom edge
MARGIN_H_RATIO = 0.02    # left and right margins (text wraps inside them)

FONT_NAME = "Arial"

_TIMING = re.compile(
    r"(\d{1,2}):(\d{2}):(\d{2})[,.](\d{1,3})\s*-->\s*(\d{1,2}):(\d{2}):(\d{2})[,.](\d{1,3})"
)
_HTML_TAG = re.compile(r"<(/?[a-zA-Z]+)[^>]*>")
_OVERRIDE_BLOCK = re.compile(r"\{[^{}]*\}")
_SIZE_OVERRIDE = re.compile(r"\\(?:fs|fscx|fscy)[\d.]+")
_HTML_TO_ASS = {
    "i": r"{\i1}",
    "/i": r"{\i0}",
    "b": r"{\b1}",
    "/b": r"{\b0}",
    "u": r"{\u1}",
    "/u": r"{\u0}",
}


def decode_subtitle(raw: bytes) -> str:
    """Decode a subtitle file. Tries UTF-8 (with or without BOM), then GB18030 (covers GBK)."""
    for encoding in ("utf-8-sig", "gb18030"):
        try:
            return raw.decode(encoding)
        except UnicodeDecodeError:
            continue
    return raw.decode("utf-8", errors="replace")


def parse_srt(text: str) -> List[Tuple[Tuple[int, int, int, int], Tuple[int, int, int, int], List[str]]]:
    """Return (start, end, text_lines) per cue; times are (h, m, s, ms)."""
    text = text.replace("\r\n", "\n").replace("\r", "\n").strip("\ufeff \n")
    cues = []
    for block in re.split(r"\n\s*\n", text):
        lines = block.split("\n")
        for index, line in enumerate(lines):
            match = _TIMING.search(line)
            if not match:
                continue
            numbers = [int(g) for g in match.groups()]
            start = tuple(numbers[0:4])
            end = tuple(numbers[4:8])
            cues.append((start, end, lines[index + 1 :]))
            break
    return cues


def _to_centiseconds(parts: Tuple[int, int, int, int]) -> int:
    hours, minutes, seconds, millis = parts
    total_ms = ((hours * 60 + minutes) * 60 + seconds) * 1000 + int(str(millis).ljust(3, "0"))
    return total_ms // 10


def _ass_time(parts: Tuple[int, int, int, int]) -> str:
    cs = _to_centiseconds(parts)
    return f"{cs // 360000}:{(cs // 6000) % 60:02d}:{(cs // 100) % 60:02d}.{cs % 100:02d}"


def _ass_text(lines: List[str]) -> str:
    """Convert SRT cue text to ASS event text (single line, \\N line breaks)."""
    out = []
    for line in lines:
        line = line.strip()
        if not line:
            continue
        # Keep ASS overrides such as {\an8} but drop size overrides so one cue cannot resize the screen.
        line = _OVERRIDE_BLOCK.sub(lambda m: _SIZE_OVERRIDE.sub("", m.group(0)), line)
        line = line.replace("{}", "")
        # Map the HTML-style tags SRT uses to ASS; drop anything else such as <font size=...>.
        line = _HTML_TAG.sub(lambda m: _HTML_TO_ASS.get(m.group(1).lower(), ""), line)
        out.append(line)
    return r"\N".join(out)


def build_ass(cues, width: int, height: int, title: str = "") -> str:
    """Build an ASS document sized for a video of width x height."""
    font_size = max(12, round(height * FONT_SIZE_RATIO))
    outline = max(1, round(height * OUTLINE_RATIO))
    margin_v = max(10, round(height * MARGIN_V_RATIO))
    margin_h = max(10, round(width * MARGIN_H_RATIO))
    header = [
        "[Script Info]",
        f"; Title: {title}" if title else "; Title: subtitles",
        "; Generated by MERGE-BOT: sized for the video resolution",
        "ScriptType: v4.00+",
        "WrapStyle: 0",
        "ScaledBorderAndShadow: yes",
        "YCbCr Matrix: None",
        f"PlayResX: {width}",
        f"PlayResY: {height}",
        "",
        "[V4+ Styles]",
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, "
        "Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, "
        "Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
        f"Style: Default,{FONT_NAME},{font_size},&H00FFFFFF,&H000000FF,&H00000000,&H80000000,"
        f"0,0,0,0,100,100,0,0,1,{outline},0,2,{margin_h},{margin_h},{margin_v},1",
        "",
        "[Events]",
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    ]
    events = []
    for start, end, lines in cues:
        body = _ass_text(lines)
        if not body:
            continue
        events.append(f"Dialogue: 0,{_ass_time(start)},{_ass_time(end)},Default,,0,0,0,,{body}")
    return "\n".join(header + events) + "\n"


def _fit_blocking(sub_path: str, width: int, height: int) -> Optional[str]:
    with open(sub_path, "rb") as fh:
        text = decode_subtitle(fh.read())
    cues = parse_srt(text)
    if not cues:
        return None
    out_path = os.path.splitext(sub_path)[0] + ".fitted.ass"
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write(build_ass(cues, width, height, title=os.path.basename(sub_path)))
    return out_path


async def fit_subtitle(sub_path: str, width: int, height: int) -> str:
    """Return the path to use for muxing this subtitle.

    SRT files become a sized ASS copy next to the original. Any other file, or a
    failure, returns the original path so the merge still goes ahead.
    """
    if not sub_path.lower().endswith(".srt"):
        return sub_path
    if not width or not height:
        width, height = 1920, 1080
    try:
        fitted = await asyncio.to_thread(_fit_blocking, sub_path, int(width), int(height))
    except Exception as err:
        LOGGER.warning(f"Could not size subtitle {sub_path}, using it as it is: {err}")
        return sub_path
    if fitted is None:
        LOGGER.warning(f"No subtitle cues found in {sub_path}, using it as it is")
        return sub_path
    return fitted


def subtitle_codec(path: str) -> str:
    """ffmpeg codec to store this subtitle with in the output MKV."""
    return "ass" if path.lower().endswith((".ass", ".ssa")) else "srt"


def video_size(streams) -> Tuple[int, int]:
    """Width and height of the first video stream (the one the merge maps)."""
    for stream in streams or []:
        if stream.get("codec_type") == "video" and stream.get("width") and stream.get("height"):
            return int(stream["width"]), int(stream["height"])
    return 1920, 1080
